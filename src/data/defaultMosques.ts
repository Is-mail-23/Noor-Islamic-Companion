export const MOSQUES_STORAGE_KEY = 'noor_app_mosques_v2';

export function loadStoredMosques(): Mosque[] {
  if (typeof window === 'undefined') return INITIAL_MOSQUES;
  try {
    const raw = localStorage.getItem(MOSQUES_STORAGE_KEY);
    if (!raw) {
      localStorage.setItem(MOSQUES_STORAGE_KEY, JSON.stringify(INITIAL_MOSQUES));
      return INITIAL_MOSQUES;
    }
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) && parsed.length > 0 ? parsed : INITIAL_MOSQUES;
  } catch (err) {
    console.error('Failed to load mosques from storage', err);
    return INITIAL_MOSQUES;
  }
}

export function saveMosques(mosques: Mosque[]) {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(MOSQUES_STORAGE_KEY, JSON.stringify(mosques));
  } catch (err) {
    console.error('Failed to save mosques', err);
  }
}
